#!/usr/bin/env python3
"""Run PAL2NAL v14 on every case in tests/cases.json and store its output as golden files.

For each case and option variant, writes to tests/golden/<case>/:
    <variant>.stdout   <variant>.stderr   <variant>.rc
Line endings are normalised to LF so goldens are identical on Windows and Linux.
PAL2NAL is run from inside the fixture folder with relative file names, so the
input paths echoed in its stderr are machine-independent.

Usage:
    python scripts/make_golden.py [--perl PERL] [--pal2nal PATH] [--case NAME ...]
"""
from __future__ import annotations

import argparse
import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIXTURES = ROOT / "tests" / "fixtures"
GOLDEN = ROOT / "tests" / "golden"
MANIFEST = ROOT / "tests" / "cases.json"
DEFAULT_PAL2NAL = ROOT / "PAL2NAL" / "pal2nal.v14" / "pal2nal.pl"


def norm(b: bytes) -> bytes:
    return b.replace(b"\r\n", b"\n")


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--perl", default="perl")
    ap.add_argument("--pal2nal", type=Path, default=DEFAULT_PAL2NAL)
    ap.add_argument("--case", nargs="*", help="only regenerate these cases")
    args = ap.parse_args()

    if not args.pal2nal.exists():
        sys.exit(f"{args.pal2nal} not found; run: python scripts/fetch_pal2nal.py")
    perl = shutil.which(args.perl) or sys.exit(f"perl not found: {args.perl}")
    pal2nal = str(args.pal2nal.resolve())

    m = json.loads(MANIFEST.read_text())
    cases = m["cases"]
    for name in args.case or []:
        if name not in cases:
            sys.exit(f"unknown case {name}")
    selected = args.case or list(cases)

    for name in selected:
        spec = cases[name]
        fx = FIXTURES / name
        out = GOLDEN / name
        out.mkdir(parents=True, exist_ok=True)
        variants = {**m["variants"], **spec.get("extra_variants", {})}
        for vname, opts in variants.items():
            cmd = [perl, pal2nal, spec["pep"], "nuc.fasta", *opts]
            r = subprocess.run(cmd, cwd=fx, capture_output=True, timeout=60)
            (out / f"{vname}.stdout").write_bytes(norm(r.stdout))
            (out / f"{vname}.stderr").write_bytes(norm(r.stderr))
            (out / f"{vname}.rc").write_text(f"{r.returncode}\n", newline="\n")
        print(f"{name}: {len(variants)} variants")

    pv = subprocess.run([perl, "-e", "print $^V"], capture_output=True, text=True).stdout.strip()
    sha = hashlib.sha256(Path(pal2nal).read_bytes()).hexdigest()
    (GOLDEN / "PROVENANCE.txt").write_text(
        f"Generated by scripts/make_golden.py\nPAL2NAL pal2nal.pl sha256: {sha}\nPerl: {pv}\nPlatform: {sys.platform}\n",
        newline="\n",
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
