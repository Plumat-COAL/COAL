"""Differential tests: COAL vs PAL2NAL v14 golden outputs (tests/golden/).

Run:  python -m unittest discover -s tests -v      (or: pytest)
No Perl or PAL2NAL needed; goldens are pre-generated by scripts/make_golden.py.

Rule, for every case and every variant (fasta, clustal, paml, codon, ...) in tests/cases.json:
  * PAL2NAL produced output  -> COAL output must be byte-identical, and COAL's
    mismatch warnings must equal PAL2NAL's.
  * PAL2NAL produced nothing (it failed) -> COAL must exit non-zero.
  * Deliberate differences (DELIBERATE below, documented in tests/README.md)
    are checked against COAL's own expected behaviour instead.
"""
from __future__ import annotations

import io
import json
import os
import re
import sys
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from coal.cli import main as coal_main  # noqa: E402

FIX = ROOT / "tests" / "fixtures"
GOLD = ROOT / "tests" / "golden"
MANIFEST = json.loads((ROOT / "tests" / "cases.json").read_text())

# (case, variant) -> what COAL does instead. "error" = must exit non-zero;
# "same_output" = output identical to PAL2NAL but warnings differ.
DELIBERATE = {
    # PAL2NAL silently drops a codon after an invalid protein character.
    **{("invalid_chars", v): "error"
       for v in ("fasta", "clustal", "paml", "codon", "fasta_nogap", "fasta_nomismatch")},
}
# NCBI vs PAL2NAL tables: table 10 TGA = Cys (PAL2NAL: stop); tables 11/13 start ATA etc.
for t, kind in ((10, "same_output"), (11, "differs"), (13, "differs")):
    for v in (f"fasta_ct{t}", f"fasta_nogap_ct{t}", f"fasta_nomismatch_ct{t}"):
        DELIBERATE[(f"table{t}", v)] = kind
DELIBERATE[("table10", "fasta_nomismatch_ct10")] = "differs"  # PAL2NAL drops the TGA columns


def run_coal(case: str, opts: list[str]):
    spec = MANIFEST["cases"][case]
    args = [spec["pep"], *spec.get("nuc", ["nuc.fasta"])]
    # PAL2NAL options are passed unchanged (COAL accepts the same spelling)
    o = list(opts)
    out, err = io.StringIO(), io.StringIO()
    cwd = os.getcwd()
    os.chdir(FIX / case)
    try:
        with redirect_stdout(out), redirect_stderr(err):
            try:
                rc = coal_main(args + o)
            except SystemExit as e:  # argparse errors
                rc = e.code
    finally:
        os.chdir(cwd)
    return rc, out.getvalue(), err.getvalue()


def warnings_of(text: str) -> list[str]:
    return sorted(re.findall(r"(\S+ pepAlnPos \d+: .*)", text))


def all_variants():
    for case, spec in MANIFEST["cases"].items():
        variants = {**MANIFEST["variants"], **spec.get("extra_variants", {})}
        for v, opts in variants.items():
            yield case, v, opts


class TestAgainstPal2nal(unittest.TestCase):
    def test_all_cases(self):
        n = 0
        for case, v, opts in all_variants():
            with self.subTest(case=case, variant=v):
                n += 1
                g_out = (GOLD / case / f"{v}.stdout").read_text()
                g_err = (GOLD / case / f"{v}.stderr").read_text()
                rc, out, err = run_coal(case, opts)
                kind = DELIBERATE.get((case, v))
                if kind == "error":
                    self.assertNotEqual(rc, 0)
                elif kind == "differs":
                    self.assertEqual(rc, 0, err)
                elif not g_out:
                    self.assertNotEqual(rc, 0, f"PAL2NAL failed but COAL succeeded:\n{out}")
                    self.assertEqual(out, "")
                else:
                    self.assertEqual(rc, 0, err)
                    self.assertEqual(out, g_out)
                    if kind != "same_output" and "-nomismatch" not in opts:
                        self.assertEqual(warnings_of(err), warnings_of(g_err))
        self.assertGreater(n, 200)


class TestCoalOwnBehaviour(unittest.TestCase):
    def test_invalid_char_is_error(self):
        rc, out, err = run_coal("invalid_chars", [])
        self.assertEqual(rc, 1)
        self.assertIn("invalid protein alignment characters", err)

    def test_table10_tga_is_cys(self):
        rc, out, err = run_coal("table10", ["-codontable", "10"])
        self.assertEqual(rc, 0)
        self.assertNotIn("does not correspond", err)

    def test_ncbi_alternative_starts(self):
        for t in (11, 13):
            rc, out, err = run_coal(f"table{t}", ["-codontable", str(t)])
            self.assertEqual(rc, 0)
            self.assertTrue(out.startswith(">s0\nATA"), out[:20])
            self.assertNotIn("does not correspond", err)

    def test_codon_format_rejects_column_removal(self):
        # PAL2NAL refuses "-output codon" with -nogap / -nomismatch; so does COAL.
        for flag in ("-nogap", "-nomismatch"):
            rc, out, err = run_coal("clean", ["-output", "codon", flag])
            self.assertEqual(rc, 1)
            self.assertEqual(out, "")

    def test_paml_and_clustal_with_column_removal(self):
        # Not covered by the goldens: same rows as FASTA, different layout.
        for flag in ("-nogap", "-nomismatch"):
            _, fa, _ = run_coal("inframe_stop", ["-output", "fasta", flag])
            seqs = [l for l in fa.splitlines() if not l.startswith(">")]
            rc, pm, _ = run_coal("inframe_stop", ["-output", "paml", flag])
            self.assertEqual(rc, 0)
            self.assertEqual(pm.splitlines()[0], f"{len(seqs):4d}{len(seqs[0]):7d}")
            self.assertEqual(pm.splitlines()[2::2], seqs)
            rc, cl, _ = run_coal("inframe_stop", ["-output", "clustal", flag])
            self.assertEqual(rc, 0)
            self.assertEqual([l.split()[1] for l in cl.splitlines()[2:] if l], seqs)

    def test_unknown_table_rejected(self):
        rc, _, _ = run_coal("clean", ["-codontable", "7"])
        self.assertNotEqual(rc, 0)


if __name__ == "__main__":
    unittest.main()
