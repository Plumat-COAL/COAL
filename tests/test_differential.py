"""Differential tests: COAL vs PAL2NAL v14 golden outputs (tests/golden/).

Run:  python -m unittest discover -s tests -v      (or: pytest)
No Perl or PAL2NAL needed; goldens are pre-generated by scripts/make_golden.py.

Engine under test: COAL_IMPL=python (default, in-process) or COAL_IMPL=cpp (the coal-cpp executable; path from
COAL_CPP_BIN, default ./build/coal-cpp). The cpp run is skipped if the binary has not been built.
`python tests/test_differential.py --count` prints the passing/total golden checks for COAL_IMPL.

Rule, for every case and every variant in tests/cases.json (all four output formats):
  * Exit status: PAL2NAL always exits 0, even on error (every golden .rc is
    checked to be 0), so its success is "exit 0 and non-empty stdout". COAL
    must exit 0 exactly when PAL2NAL succeeded, non-zero otherwise.
  * PAL2NAL produced output  -> COAL output must be byte-identical, and COAL's
    per-codon warnings ("<id> pepAlnPos N: ...") must equal PAL2NAL's, with
    or without -nomismatch.
  * PAL2NAL produced nothing (it failed) -> COAL must exit non-zero with empty stdout.
  * Deliberate differences (DELIBERATE below, documented in tests/README.md)
    are checked against COAL's own expected behaviour instead.
The test prints the number of each kind of check it made (tests/README.md quotes them).
"""
from __future__ import annotations

import io
import json
import os
import re
import subprocess
import sys
import unittest
from contextlib import redirect_stderr, redirect_stdout
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))
from coal.cli import main as coal_main  # noqa: E402

FIX = ROOT / "tests" / "fixtures"
GOLD = ROOT / "tests" / "golden"
MANIFEST = json.loads((ROOT / "tests" / "cases.json").read_text())
IMPL = os.environ.get("COAL_IMPL", "python").lower()
N_CHECKS = 285  # every stored golden check


def cpp_binary() -> Path | None:
    p = Path(os.environ.get("COAL_CPP_BIN", ROOT / "build" / "coal-cpp"))
    if not p.is_absolute():
        p = ROOT / p
    for cand in (p, p.with_suffix(".exe"), p.parent / "Release" / (p.name + ".exe")):
        # on Windows only .exe files: a shared folder may also hold the Linux build
        if cand.is_file() and (os.name != "nt" or cand.suffix.lower() == ".exe"):
            return cand
    return None

# (case, variant) -> what COAL does instead. "error" = must exit non-zero;
# "same_output" = output identical to PAL2NAL but warnings differ;
# "differs" = output differs (COAL must exit 0).
DELIBERATE = {
    # PAL2NAL silently drops a codon after an invalid protein character.
    **{("invalid_chars", v): "error" for v in ("fasta", "fasta_nogap", "fasta_nomismatch", "clustal", "paml",
                                                "codon")},
}
# NCBI vs PAL2NAL tables: table 10 TGA = Cys (PAL2NAL: stop); tables 11/13 start ATA etc.
# fasta_ct and fasta_nogap_ct: the output is byte-identical (only the warnings differ), so "same_output".
for t in (10, 11, 13):
    for v in (f"fasta_ct{t}", f"fasta_nogap_ct{t}"):
        DELIBERATE[(f"table{t}", v)] = "same_output"
    # -nomismatch: PAL2NAL drops the columns it flags (TGA in table 10, ATA starts in 11/13)
    DELIBERATE[(f"table{t}", f"fasta_nomismatch_ct{t}")] = "differs"
# -nogap removes the selected code's stop codons (PAL2NAL: always the standard code's TAA/TAG/TGA).
# COAL's output must equal PAL2NAL's output without -nogap (golden fasta_ct<N>) with COAL's -nogap rule applied.
NOGAP_CODE = {"codontable2": 2, **{f"table{t}": t for t in (2, 3, 4, 5, 6, 9, 10, 13, 14, 15, 16, 21, 22)}}
for c, t in NOGAP_CODE.items():
    DELIBERATE[(c, f"fasta_nogap_ct{t}")] = "nogap_code"


def nogap_expected(case: str, table: int) -> str:
    """PAL2NAL's -codontable N output without -nogap, with gap columns and the code's stop columns removed."""
    from coal.core import nogap_bad_triplets
    from coal.pipeline import fasta_record
    text = (GOLD / case / f"fasta_ct{table}.stdout").read_text()
    recs = [(r.split("\n", 1)[0], r.split("\n", 1)[1].replace("\n", "")) for r in text.split(">")[1:]]
    bad = set().union(*(nogap_bad_triplets(s, table) for _, s in recs))
    return "".join(fasta_record(i, "".join(s[k:k + 3] for k in range(0, len(s), 3) if k // 3 not in bad))
                   for i, s in recs)


def run_coal(case: str, opts: list[str]):
    spec = MANIFEST["cases"][case]
    args = [spec["pep"], *spec.get("nuc", ["nuc.fasta"])]
    o = list(opts)  # COAL takes PAL2NAL's options with the same spelling (incl. -output)
    o = ["--max-warnings", "0", *o]  # `coal` caps warnings at 20 by default; PAL2NAL prints all
    if IMPL == "cpp":
        r = subprocess.run([str(cpp_binary()), *args, *o], cwd=FIX / case, capture_output=True, timeout=60)
        # stdout must be byte-identical; stderr is text (CRLF on Windows, as Python's): compare its lines
        return r.returncode, r.stdout.decode("ascii", "replace"), \
            r.stderr.decode("ascii", "replace").replace("\r\n", "\n")
    out, err = io.StringIO(), io.StringIO()
    cwd = os.getcwd()
    os.chdir(FIX / case)
    try:
        with redirect_stdout(out), redirect_stderr(err):
            try:
                rc = coal_main(args + o)
            except SystemExit as e:  # argparse errors
                rc = e.code
    finally:
        os.chdir(cwd)
    return rc, out.getvalue(), err.getvalue()


def warnings_of(text: str) -> list[str]:
    return sorted(re.findall(r"(\S+ pepAlnPos \d+: .*)", text))


def all_variants():
    for case, spec in MANIFEST["cases"].items():
        variants = {**MANIFEST["variants"], **spec.get("extra_variants", {})}
        for v, opts in variants.items():
            yield case, v, opts


COUNT_KEYS = ("golden rc = 0", "COAL exit status", "stdout byte-identical", "warnings identical",
              "with -nomismatch", "both fail", "deliberate error", "deliberate same_output", "deliberate differs",
              "deliberate nogap_code")


def compare_all(tc: unittest.TestCase):
    """Run every check (assertions on `tc`); return (number of cases, number of checks, counts).
    Shared by test_all_cases and the docs-numbers guard (tests/test_docs_numbers.py)."""
    n = 0
    count = dict.fromkeys(COUNT_KEYS, 0)
    cases = set()
    for case, v, opts in all_variants():
        with tc.subTest(case=case, variant=v):
            n += 1
            cases.add(case)
            g_out = (GOLD / case / f"{v}.stdout").read_text()
            g_err = (GOLD / case / f"{v}.stderr").read_text()
            g_rc = int((GOLD / case / f"{v}.rc").read_text().strip())
            tc.assertEqual(g_rc, 0, "PAL2NAL is expected to always exit 0")
            count["golden rc = 0"] += 1
            pal_ok = g_rc == 0 and g_out != ""
            rc, out, err = run_coal(case, opts)
            kind = DELIBERATE.get((case, v))
            if kind == "error":
                tc.assertNotEqual(rc, 0)
                count["deliberate error"] += 1
                continue
            tc.assertEqual(rc == 0, pal_ok, err)
            count["COAL exit status"] += 1
            if kind == "differs":
                count["deliberate differs"] += 1
            elif kind == "nogap_code":
                tc.assertEqual(out, nogap_expected(case, NOGAP_CODE[case]))
                count["deliberate nogap_code"] += 1
            elif not pal_ok:
                tc.assertEqual(out, "")
                count["both fail"] += 1
            else:
                tc.assertEqual(out, g_out)
                count["stdout byte-identical"] += 1
                if kind == "same_output":
                    count["deliberate same_output"] += 1
                else:
                    tc.assertEqual(warnings_of(err), warnings_of(g_err))
                    count["warnings identical"] += 1
                    count["with -nomismatch"] += "-nomismatch" in opts
    return len(cases), n, count


def summary_line(ncases, n, count) -> str:
    return f"PAL2NAL comparison: {ncases} cases, {n} checks: " + ", ".join(f"{k} {v}" for k, v in count.items())


def _skip_without_engine(tc):
    if IMPL == "cpp" and cpp_binary() is None:
        tc.skipTest("coal-cpp not built (set COAL_CPP_BIN or build into ./build)")


class TestAgainstPal2nal(unittest.TestCase):
    def setUp(self):
        _skip_without_engine(self)

    def test_all_cases(self):
        ncases, n, count = compare_all(self)
        print("\n" + summary_line(ncases, n, count), file=sys.stderr)
        self.assertEqual(n, N_CHECKS)  # every stored golden


class TestCoalOwnBehaviour(unittest.TestCase):
    def setUp(self):
        _skip_without_engine(self)

    def test_invalid_char_is_error(self):
        rc, out, err = run_coal("invalid_chars", [])
        self.assertEqual(rc, 1)
        self.assertIn("invalid protein alignment characters", err)

    def test_table10_tga_is_cys(self):
        rc, out, err = run_coal("table10", ["-codontable", "10"])
        self.assertEqual(rc, 0)
        self.assertNotIn("does not correspond", err)

    def test_ncbi_alternative_starts(self):
        for t in (11, 13):
            rc, out, err = run_coal(f"table{t}", ["-codontable", str(t)])
            self.assertEqual(rc, 0)
            self.assertTrue(out.startswith(">s0\nATA"), out[:20])
            self.assertNotIn("does not correspond", err)

    def test_codon_format_rejects_column_removal(self):
        # PAL2NAL refuses "-output codon" with -nogap / -nomismatch; so does COAL.
        for flag in ("-nogap", "-nomismatch"):
            rc, out, err = run_coal("clean", ["-output", "codon", flag])
            self.assertEqual(rc, 1)
            self.assertEqual(out, "")

    def test_paml_and_clustal_with_column_removal(self):  # PAML header as PAL2NAL's
        # Not covered by the goldens: same rows as FASTA, different layout.
        for flag in ("-nogap", "-nomismatch"):
            _, fa, _ = run_coal("inframe_stop", ["-output", "fasta", flag])
            seqs = [l for l in fa.splitlines() if not l.startswith(">")]
            rc, pm, _ = run_coal("inframe_stop", ["-output", "paml", flag])
            self.assertEqual(rc, 0)
            self.assertEqual(pm.splitlines()[0], " %3d %6d" % (len(seqs), len(seqs[0])))
            self.assertEqual(pm.splitlines()[2::2], seqs)
            rc, cl, _ = run_coal("inframe_stop", ["-output", "clustal", flag])
            self.assertEqual(rc, 0)
            self.assertEqual([l.split()[1] for l in cl.splitlines()[2:] if l], seqs)

    def test_unknown_table_rejected(self):
        rc, _, _ = run_coal("clean", ["-codontable", "7"])
        self.assertNotEqual(rc, 0)


if __name__ == "__main__":
    class _Collect(unittest.TestCase):
        """compare_all() without stopping at the first failure: records each failing (case, variant)."""

        def runTest(self):
            pass

        def __init__(self):
            super().__init__()
            self.fails = []

        def subTest(self, msg=None, **params):  # noqa: D401 - collects instead of failing
            import contextlib

            @contextlib.contextmanager
            def cm():
                try:
                    yield
                except AssertionError as e:
                    self.fails.append(f"{params.get('case')}/{params.get('variant')}: {str(e)[:200]}")
            return cm()

    if sys.argv[1:] == ["--count"]:  # print "passing/total" golden checks for COAL_IMPL
        if IMPL == "cpp" and cpp_binary() is None:
            print("cpp: skipped (coal-cpp not built; set COAL_CPP_BIN or build into ./build)")
            sys.exit(0)
        tc = _Collect()
        ncases, n, count = compare_all(tc)
        print("\n".join(tc.fails))
        print(f"{IMPL}: {n - len(tc.fails)}/{n} golden checks")
        print(summary_line(ncases, n, count))
        sys.exit(1 if tc.fails else 0)
    unittest.main()
