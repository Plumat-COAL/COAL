"""Differential tests: COAL vs PAL2NAL v14 golden outputs (tests/golden/).

Run:  python -m unittest discover -s tests -v      (or: pytest)
No Perl or PAL2NAL needed; goldens are pre-generated by scripts/make_golden.py.
"""
from __future__ import annotations

import json
import os
import subprocess
import sys
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FIX = ROOT / "tests" / "fixtures"
GOLD = ROOT / "tests" / "golden"
CASES = json.loads((ROOT / "tests" / "cases.json").read_text())["cases"]

# Cases where COAL v0.1 must reproduce PAL2NAL's FASTA output byte-for-byte.
MATCH_PAL2NAL = [
    "clean", "clustal_input", "multiline_fasta", "lowercase", "rna",
    "unordered_ids", "id_mismatch_same_order", "inframe_stop",
    "terminal_stop", "ambiguous_bases",
]

# Cases where COAL v0.1 must fail with a non-zero exit and an error message.
# (PAL2NAL also errors on the first four; the rest are out of MVP scope or
#  deliberate differences -- see tests/README.md.)
MUST_ERROR = {
    "id_mismatch_count": "number of sequences differs",
    "empty_protein": "number of sequences differs",
    "codon_mismatch": "does not encode",
    "codontable2": "does not encode",
    "invalid_chars": "invalid protein characters",  # PAL2NAL silently drops a codon
    "frameshift": "frameshift",                       # not supported yet
    "utr": "DNA length",                              # not supported yet
}


def run_coal(case: str) -> subprocess.CompletedProcess:
    env = {**os.environ, "PYTHONPATH": str(ROOT / "src")}
    return subprocess.run(
        [sys.executable, "-m", "coal", CASES[case]["pep"], "nuc.fasta"],
        cwd=FIX / case, capture_output=True, env=env, timeout=60,
    )


class TestMatchesPal2nal(unittest.TestCase):
    def test_fasta_output_identical(self):
        for case in MATCH_PAL2NAL:
            with self.subTest(case=case):
                r = run_coal(case)
                self.assertEqual(r.returncode, 0, r.stderr.decode())
                expected = (GOLD / case / "fasta.stdout").read_bytes()
                self.assertEqual(r.stdout.replace(b"\r\n", b"\n"), expected)


class TestErrors(unittest.TestCase):
    def test_errors_are_reported(self):
        for case, msg in MUST_ERROR.items():
            with self.subTest(case=case):
                r = run_coal(case)
                self.assertNotEqual(r.returncode, 0)
                self.assertEqual(r.stdout, b"")
                self.assertIn(msg, r.stderr.decode())


class TestCoverage(unittest.TestCase):
    def test_every_case_is_classified(self):
        self.assertEqual(set(CASES), set(MATCH_PAL2NAL) | set(MUST_ERROR))


if __name__ == "__main__":
    unittest.main()
